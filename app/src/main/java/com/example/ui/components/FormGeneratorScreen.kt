    var quickPasteOpen by remember { mutableStateOf(false) }
    var rawQuoteInput by remember { mutableStateOf("") }
    var justGenerated by remember { mutableStateOf(false) }

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(StudioColors.Surface)
    ) {
        // Header strip
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .background(StudioColors.SurfaceMuted)
                .padding(horizontal = 16.dp, vertical = 12.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.SpaceBetween
        ) {
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = "Document Generator",
                    style = MaterialTheme.typography.titleMedium,
                    color = StudioColors.TextPrimary
                )
                Text(
                    text = "Fill client & event fields — A4 preview updates live",
                    style = MaterialTheme.typography.bodySmall,
                    color = StudioColors.TextMuted
                )
            }
            OutlinedButton(
                onClick = { onStartNewClient(); justGenerated = false },
                shape = RoundedCornerShape(10.dp),
                contentPadding = PaddingValues(horizontal = 12.dp, vertical = 8.dp),
                modifier = Modifier
                    .defaultMinSize(minHeight = 48.dp)
                    .testTag("new_client_button")
            ) {
                Icon(Icons.Default.PersonAdd, contentDescription = null, modifier = Modifier.size(16.dp))
                Spacer(modifier = Modifier.width(6.dp))
                Text("New Client", fontSize = 12.sp)
            }
        }
        HorizontalDivider(color = StudioColors.Border)

        // Scrollable form sections
        Column(
            modifier = Modifier
                .weight(1f)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            // Document Title
            StudioTextField(
                label = "Document Title (Workspace Name)",
                value = projectName,
                onValueChange = onProjectNameChange,
                testTag = "project_name_input"
            )

            // Quick Quote Auto-Fill Accordion
            Surface(
                shape = RoundedCornerShape(12.dp),
                color = StudioColors.BrandSoftBg,
                border = BorderStroke(1.dp, StudioColors.BrandSoftBorder)
            ) {
                Column(modifier = Modifier.fillMaxWidth()) {
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .defaultMinSize(minHeight = 48.dp)
                            .testTag("quick_quote_toggle")
                            .clickable { quickPasteOpen = !quickPasteOpen }
                            .padding(horizontal = 12.dp, vertical = 10.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(8.dp)
                        ) {
                            Icon(
                                Icons.Default.AutoFixHigh,
                                contentDescription = null,
                                tint = StudioColors.BrandAccent,
                                modifier = Modifier.size(18.dp)
                            )
                            Text(
                                text = "Quick Quote Auto-Fill (WhatsApp / Notes)",
                                style = MaterialTheme.typography.labelMedium,
                                fontWeight = FontWeight.Bold,
                                color = Color(0xFF9A3412)
                            )
                        }
                        Icon(
                            imageVector = if (quickPasteOpen) Icons.Default.ExpandLess else Icons.Default.ExpandMore,
                            contentDescription = "Toggle Quick Quote Auto-Fill",
                            tint = StudioColors.BrandAccent
                        )
                    }

                    AnimatedVisibility(visible = quickPasteOpen) {
                        Column(
                            modifier = Modifier
                                .fillMaxWidth()
                                .background(StudioColors.Surface)
                                .padding(12.dp),
                            verticalArrangement = Arrangement.spacedBy(10.dp)
                        ) {
                            OutlinedTextField(
                                value = rawQuoteInput,
                                onValueChange = { rawQuoteInput = it },
                                label = { Text("Paste WhatsApp quotation note") },
                                placeholder = { Text("Date: 13/11/2026 Pax: 200 Client: ...") },
                                minLines = 3,
                                maxLines = 6,
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .testTag("quick_quote_input")
                            )
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.spacedBy(8.dp)
                            ) {
                                OutlinedButton(
                                    onClick = { rawQuoteInput = QuoteParser.SUNCULTURE_SAMPLE_QUOTE },
                                    modifier = Modifier
                                        .weight(1f)
                                        .defaultMinSize(minHeight = 48.dp)
                                        .testTag("load_sample_quote_button")
                                ) {
                                    Text("Load Sample", fontSize = 12.sp)
                                }
                                Button(
                                    onClick = {
                                        onApplyRawQuote(rawQuoteInput)
                                        quickPasteOpen = false
                                    },
                                    enabled = rawQuoteInput.isNotBlank(),
                                    colors = ButtonDefaults.buttonColors(containerColor = StudioColors.BrandAccent),
                                    modifier = Modifier
                                        .weight(1f)
                                        .defaultMinSize(minHeight = 48.dp)
                                        .testTag("apply_quote_button")
                                ) {
                                    Text("Populate Form", fontSize = 12.sp)
                                }
                            }
                        }
                    }
                }
            }

            // Section A: Document Details
            SectionHeader(letter = "A", title = "Document Details")
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                StudioTextField(
                    label = "Event Date",
                    value = formData.date,
                    onValueChange = { v -> onUpdateField({ it.copy(date = v) }, null) },
                    placeholder = "13/11/2026",
                    modifier = Modifier.weight(1f),
                    testTag = "form_date_input"
                )
                StudioTextField(
                    label = "PAX / Guests",
                    value = formData.pax,
                    onValueChange = { v -> onUpdateField({ it.copy(pax = v) }, null) },
                    placeholder = "200",
                    modifier = Modifier.weight(1f),
                    testTag = "form_pax_input"
                )
            }
            StudioTextField(
                label = "Client Name",
                value = formData.clientName,
                onValueChange = { v -> onUpdateField({ it.copy(clientName = v) }, null) },
                placeholder = "Sunculture Kenya Ltd",
                testTag = "form_client_input"
            )
            StudioTextField(
                label = "Venue / Location",
                value = formData.venue,
                onValueChange = { v -> onUpdateField({ it.copy(venue = v) }, null) },
                placeholder = "Muthangari Drive",
                testTag = "form_venue_input"
            )

            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Text(
                    text = "Event Details / Quotation Body",
                    style = MaterialTheme.typography.labelMedium,
                    color = StudioColors.TextSecondary
                )
                TextButton(
                    onClick = onCleanMenuBullets,
                    modifier = Modifier
                        .defaultMinSize(minHeight = 48.dp)
                        .testTag("clean_bullets_button")
                ) {
                    Icon(Icons.Default.CleaningServices, contentDescription = null, modifier = Modifier.size(15.dp))
                    Spacer(modifier = Modifier.width(4.dp))
                    Text("Clean Bullets", fontSize = 12.sp)
                }
            }
            OutlinedTextField(
                value = formData.eventDetails,
                onValueChange = { v ->
                    val updated = if (v.length > formData.eventDetails.length && v.endsWith("\n")) {
                        "$v•  "
                    } else {
                        v
                    }
                    onUpdateField({ it.copy(eventDetails = updated) }, null)
                },
                minLines = 6,
                maxLines = 12,
                colors = OutlinedTextFieldDefaults.colors(
                    focusedBorderColor = StudioColors.BrandAccent,
                    unfocusedBorderColor = StudioColors.Border
                ),
                modifier = Modifier
                    .fillMaxWidth()
                    .testTag("form_event_details_input")
            )

            // Supervisor Toggle: Show/Hide Quantity & Price on Menu
            Surface(
                shape = RoundedCornerShape(10.dp),
                color = StudioColors.SurfaceMuted,
                border = BorderStroke(1.dp, StudioColors.Border)
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 12.dp, vertical = 8.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Column(modifier = Modifier.weight(1f)) {
                        Text(
                            text = "Show Quantity & Price on Menu",
                            style = MaterialTheme.typography.labelMedium,
                            fontWeight = FontWeight.SemiBold,
                            color = StudioColors.TextPrimary
                        )
                        Text(
                            text = "Supervisor option: hide per-plate prices/quantities on client menu",
                            style = MaterialTheme.typography.bodySmall,
                            color = StudioColors.TextMuted
                        )
                    }
                    Switch(
                        checked = formData.showMenuQuantityAndPrice,
                        onCheckedChange = { checked ->
                            onUpdateField({ it.copy(showMenuQuantityAndPrice = checked) }, null)
                        },
                        colors = SwitchDefaults.colors(checkedTrackColor = StudioColors.BrandAccent),
                        modifier = Modifier.testTag("supervisor_qty_price_switch")
                    )
                }
            }

            HorizontalDivider(color = StudioColors.Border)

            // Section B: Payment Information
            SectionHeader(letter = "B", title = "Payment Information (Kenya 16% VAT)")
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                StudioTextField(
                    label = "Transport Cost",
                    value = formData.transportCost,
                    onValueChange = { v -> onUpdateField({ it.copy(transportCost = FormSync.formatNumericInput(v)) }, null) },
                    modifier = Modifier.weight(1f),
                    testTag = "form_transport_input"
                )
                StudioTextField(
                    label = "Subtotal (Excl. VAT)",
                    value = formData.subtotalCost,
                    onValueChange = { v -> onUpdateField({ it.copy(subtotalCost = FormSync.formatNumericInput(v)) }, "subtotalCost") },
                    modifier = Modifier.weight(1f),
                    testTag = "form_subtotal_input"
                )
            }
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                StudioTextField(
                    label = "VAT (16% Kenya)",
                    value = formData.vatAmount,
                    onValueChange = { v -> onUpdateField({ it.copy(vatAmount = FormSync.formatNumericInput(v)) }, "vatAmount") },
                    modifier = Modifier.weight(1f),
                    testTag = "form_vat_input"
                )
                StudioTextField(
                    label = "Total Amount",
                    value = formData.totalAmount,
                    onValueChange = { v -> onUpdateField({ it.copy(totalAmount = FormSync.formatNumericInput(v)) }, "totalAmount") },
                    modifier = Modifier.weight(1f),
                    testTag = "form_total_input"
                )
            }
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                StudioTextField(
                    label = "Deposit Amount",
                    value = formData.depositAmount,
                    onValueChange = { v -> onUpdateField({ it.copy(depositAmount = FormSync.formatNumericInput(v)) }, "depositAmount") },
                    modifier = Modifier.weight(1f),
                    testTag = "form_deposit_input"
                )
                StudioTextField(
                    label = "Balance Due",
                    value = formData.balance,
                    onValueChange = { v -> onUpdateField({ it.copy(balance = FormSync.formatNumericInput(v)) }, null) },
                    modifier = Modifier.weight(1f),
                    testTag = "form_balance_input"
                )
            }
            StudioTextField(
                label = "Payment Method",
                value = formData.paymentMethod,
                onValueChange = { v -> onUpdateField({ it.copy(paymentMethod = v) }, null) },
                testTag = "form_payment_method_input"
            )
            StudioTextField(
                label = "Bank Details",
                value = formData.bankDetails,
                onValueChange = { v -> onUpdateField({ it.copy(bankDetails = v) }, null) },
                singleLine = false,
                minLines = 3,
                testTag = "form_bank_details_input"
            )
            StudioTextField(
                label = "M-Pesa / Till Details",
                value = formData.mpesaDetails,
                onValueChange = { v -> onUpdateField({ it.copy(mpesaDetails = v) }, null) },
                singleLine = false,
                minLines = 2,
                testTag = "form_mpesa_details_input"
            )
            StudioTextField(
                label = "Payment Instructions / Closing Note",
                value = formData.paymentInstructions,
                onValueChange = { v -> onUpdateField({ it.copy(paymentInstructions = v) }, null) },
                singleLine = false,
                minLines = 2,
                testTag = "form_payment_instructions_input"
            )

            HorizontalDivider(color = StudioColors.Border)

            // Section C: Sender Details
            SectionHeader(letter = "C", title = "Sender Details")
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                StudioTextField(
                    label = "Company Name",
                    value = formData.companyName,
                    onValueChange = { v -> onUpdateField({ it.copy(companyName = v) }, null) },
                    modifier = Modifier.weight(1f),
                    testTag = "form_company_name_input"
                )
                StudioTextField(
                    label = "Contact Person / Desk",
                    value = formData.contactPerson,
                    onValueChange = { v -> onUpdateField({ it.copy(contactPerson = v) }, null) },
                    modifier = Modifier.weight(1f),
                    testTag = "form_contact_person_input"
                )
            }
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                StudioTextField(
                    label = "Phone Number",
                    value = formData.phoneNumber,
                    onValueChange = { v -> onUpdateField({ it.copy(phoneNumber = v) }, null) },
                    modifier = Modifier.weight(1f),
                    testTag = "form_phone_input"
                )
                StudioTextField(
                    label = "Email",
                    value = formData.email,
                    onValueChange = { v -> onUpdateField({ it.copy(email = v) }, null) },
                    modifier = Modifier.weight(1f),
                    testTag = "form_email_input"
                )
            }
            StudioTextField(
                label = "Physical Address",
                value = formData.physicalAddress,
                onValueChange = { v -> onUpdateField({ it.copy(physicalAddress = v) }, null) },
                testTag = "form_physical_address_input"
            )
            StudioTextField(
                label = "Postal Address",
                value = formData.postalAddress,
                onValueChange = { v -> onUpdateField({ it.copy(postalAddress = v) }, null) },
                testTag = "form_postal_address_input"
            )
            OutlinedButton(
                onClick = { onSavePermanentAddress(formData.physicalAddress, formData.postalAddress) },
                shape = RoundedCornerShape(10.dp),
                modifier = Modifier
                    .fillMaxWidth()
                    .defaultMinSize(minHeight = 48.dp)
                    .testTag("save_permanent_address_button")
            ) {
                Icon(Icons.Default.Save, contentDescription = null, modifier = Modifier.size(16.dp))
                Spacer(modifier = Modifier.width(6.dp))
                Text("Set / Update Permanent Address", fontSize = 12.sp)
            }

            Spacer(modifier = Modifier.height(12.dp))
        }

        // Sticky Footer Actions
        HorizontalDivider(color = StudioColors.Border)
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .background(StudioColors.SurfaceMuted)
                .navigationBarsPadding()
                .padding(horizontal = 14.dp, vertical = 10.dp),
            horizontalArrangement = Arrangement.spacedBy(8.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Button(
                onClick = {
                    onGenerateDocument()
                    justGenerated = true
                },
                colors = ButtonDefaults.buttonColors(
                    containerColor = if (justGenerated) StudioColors.SuccessText else StudioColors.BrandAccent
                ),
                shape = RoundedCornerShape(10.dp),
                contentPadding = PaddingValues(horizontal = 16.dp, vertical = 12.dp),
                modifier = Modifier
                    .defaultMinSize(minWidth = 56.dp, minHeight = 48.dp)
                    .testTag("generate_document_button")
            ) {
                Icon(
                    imageVector = Icons.Default.Check,
                    contentDescription = "Generate Document",
                    modifier = Modifier.size(22.dp)
                )
            }

            if (isCompactLayout) {
                OutlinedButton(
                    onClick = onShowPreviewCompact,
                    shape = RoundedCornerShape(10.dp),
                    modifier = Modifier
                        .defaultMinSize(minHeight = 48.dp)
                        .testTag("preview_a4_button")
                ) {
                    Icon(Icons.Default.Visibility, contentDescription = null, modifier = Modifier.size(16.dp))
                    Spacer(modifier = Modifier.width(5.dp))
                    Text("Preview", fontSize = 13.sp)
                }
            }

            OutlinedButton(
                onClick = onSwitchToVisual,
                shape = RoundedCornerShape(10.dp),
                modifier = Modifier
                    .defaultMinSize(minHeight = 48.dp)
                    .testTag("edit_visually_button")
            ) {
                Icon(Icons.Default.Edit, contentDescription = null, modifier = Modifier.size(16.dp))
                Spacer(modifier = Modifier.width(5.dp))
                Text("Edit Visually", fontSize = 13.sp)
            }
        }
    }
}

@Composable
private fun SectionHeader(letter: String, title: String) {
    Row(
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        Surface(
            shape = RoundedCornerShape(6.dp),
            color = StudioColors.BrandSoftBg,
            border = BorderStroke(1.dp, StudioColors.BrandSoftBorder)
        ) {
            Text(
                text = letter,
                style = MaterialTheme.typography.labelMedium,
                fontWeight = FontWeight.Bold,
                color = StudioColors.BrandAccent,
                modifier = Modifier.padding(horizontal = 8.dp, vertical = 2.dp)
            )
        }
        Text(
            text = title.uppercase(),
            style = MaterialTheme.typography.titleSmall,
            color = StudioColors.TextPrimary,
            letterSpacing = 0.6.sp
        )
    }
}

@Composable
private fun StudioTextField(
    label: String,
    value: String,
    onValueChange: (String) -> Unit,
    testTag: String,
    modifier: Modifier = Modifier,
    placeholder: String = "",
    singleLine: Boolean = true,
    minLines: Int = 1
) {
    OutlinedTextField(
        value = value,
        onValueChange = onValueChange,
        label = { Text(label, fontSize = 12.sp) },
        placeholder = if (placeholder.isNotEmpty()) {
            { Text(placeholder, fontSize = 12.sp, color = StudioColors.TextMuted) }
        } else null,
        singleLine = singleLine,
        minLines = minLines,
        maxLines = if (singleLine) 1 else 6,
        colors = OutlinedTextFieldDefaults.colors(
            focusedBorderColor = StudioColors.BrandAccent,
            unfocusedBorderColor = StudioColors.Border,
            focusedLabelColor = StudioColors.BrandAccent
        ),
        shape = RoundedCornerShape(10.dp),
        modifier = modifier
            .fillMaxWidth()
            .testTag(testTag)
    )
}
