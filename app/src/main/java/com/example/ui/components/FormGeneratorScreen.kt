    projectName: String,
    formData: LetterheadFormData,
    isCompactLayout: Boolean,
    onProjectNameChange: (String) -> Unit,
    onUpdateField: (transform: (LetterheadFormData) -> LetterheadFormData, recalcFrom: String?) -> Unit,
    onApplyRawQuote: (String) -> Unit,
    onCleanMenuBullets: () -> Unit,
    onGenerateDocument: () -> Unit,
    onStartNewClient: () -> Unit,
    onSwitchToVisual: () -> Unit,
    onShowPreviewCompact: () -> Unit,
    onSavePermanentAddress: (String, String) -> Unit = { _, _ -> },
    modifier: Modifier = Modifier
